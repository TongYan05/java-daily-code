/**
 * ============================================================================
 * ANU COMP7710 (12学分) Java 编程核心考点预测与复习大纲
 * ============================================================================
 * 
 * 课程背景：
 * COMP7710 是 ANU 新开设的 12 学分核心课，相比之前的 6 学分课程，其深度和广度均有显著增加。
 * 目标不仅是掌握语法，更要具备“面向对象设计”思维和解决复杂工程问题的能力。
 * 
 * ----------------------------------------------------------------------------
 * 模块一：Java 基础与内存模型 (Foundation & Memory)
 * ----------------------------------------------------------------------------
 * 1. 数据类型与转换:
 *    - 基本数据类型 (int, double, boolean...) vs 包装类 (Integer, Double...)
 *    - **考点**: 自动装箱 (Autoboxing) 与自动拆箱 (Unboxing) 的原理及性能陷阱。
 *    - **考点**: String 的不可变性 (Immutability) 以及 String Pool (字符串常量池) 机制。
 *    - **考点**: `==` (地址比较) 与 `.equals()` (内容比较) 的区别。
 * 
 * 2. 数组与字符串处理:
 *    - 一维/二维数组的内存布局。
 *    - StringBuilder/StringBuffer 的使用场景（高频字符串拼接）。
 *    - **考点**: 常用 API (substring, indexOf, split, toCharArray) 的底层逻辑。
 * 
 * 3. 流程控制与逻辑:
 *    - 循环嵌套的逻辑追踪 (Trace code)。
 *    - **考点**: Break/Continue 在多层循环中的跳转逻辑。
 * 
 * ----------------------------------------------------------------------------
 * 模块二：面向对象编程核心 (OOP Core) - **重中之重**
 * ----------------------------------------------------------------------------
 * 1. 类与对象 (Class & Object):
 *    - 构造方法 (Constructor) 的重载与 `this` 关键字。
 *    - 访问修饰符 (private, default, protected, public) 的权限边界。
 *    - **考点**: Static 关键字（静态变量、静态方法、静态代码块的执行顺序）。
 * 
 * 2. 继承与多态 (Inheritance & Polymorphism):
 *    - `extends` 关键字与 `super` 的使用。
 *    - **考点**: 方法重写 (Override) vs 方法重载 (Overload) 的严格定义。
 *    - **考点**: 向上转型 (Upcasting) 与动态绑定 (Dynamic Binding) 的执行过程。
 *    - **考点**: `instanceof` 关键字在类型安全判断中的应用。
 *    - **考点**: Object 类中的核心方法 (`toString`, `equals`, `hashCode`) 的重写规范。
 * 
 * 3. 抽象与接口 (Abstraction & Interface):
 *    - 抽象类 (Abstract Class) 与接口 (Interface) 的设计选择。
 *    - **考点**: JDK 8+ 接口中默认方法 (Default Method) 和静态方法的使用。
 *    - **考点**: 为什么 Java 不支持多重继承但支持多实现？(Diamond Problem)。
 * 
 * ----------------------------------------------------------------------------
 * 模块三：高级特性与集合框架 (Advanced Features & Collections)
 * ----------------------------------------------------------------------------
 * 1. 泛型 (Generics):
 *    - 泛型类、泛型方法、泛型接口的定义。
 *    - **考点**: 泛型通配符 `?` (Upper bound `? extends T` / Lower bound `? super T`)。
 *    - **考点**: 类型擦除 (Type Erasure) 的概念及其对运行时的影响。
 * 
 * 2. 集合框架 (Collections Framework):
 *    - List (ArrayList, LinkedList), Set (HashSet, TreeSet), Map (HashMap, TreeMap)。
 *    - **考点**: HashMap 的底层原理 (Hash 冲突解决、扩容机制)。
 *    - **考点**: Comparable 接口 vs Comparator 接口的排序实现。
 *    - **考点**: 迭代器 (Iterator) 的安全删除操作。
 * 
 * 3. 异常处理 (Exception Handling):
 *    - Checked Exception (编译时异常) vs Unchecked Exception (运行时异常)。
 *    - **考点**: try-catch-finally 的执行顺序（尤其是 finally 中有 return 的情况）。
 *    - **考点**: 自定义异常类的设计与抛出 (throw/throws)。
 * 
 * ----------------------------------------------------------------------------
 * 模块四：工程化与新特性 (Engineering & New Features)
 * ----------------------------------------------------------------------------
 * 1. 文件 I/O 与序列化:
 *    - 使用 Scanner/FileReader 读取文本文件。
 *    - **考点**: 对象的序列化 (Serializable) 与反序列化。
 * 
 * 2. Lambda 表达式与 Stream API (JDK 8+):
 *    - 函数式接口 (Functional Interface) 的理解。
 *    - **考点**: 使用 Stream 进行集合的过滤 (filter)、映射 (map) 和归约 (reduce)。
 * 
 * 3. 多线程基础 (Concurrency Basics):
 *    - Thread 类与 Runnable 接口的区别。
 *    - **考点**: 线程同步 (Synchronized) 与线程安全问题。
 * 
 * ----------------------------------------------------------------------------
 * 模块五：设计与调试 (Design & Debugging)
 * ----------------------------------------------------------------------------
 * 1. 设计模式入门:
 *    - Singleton (单例模式): 确保一个类只有一个实例。
 *    - Factory (工厂模式): 简化对象创建过程。
 *    - **考点**: 在 Assignment 中识别并应用合适的设计模式。
 * 
 * 2. 单元测试 (JUnit):
 *    - **考点**: 编写测试用例验证业务逻辑，理解 Assert 断言。
 * 
 * 3. 代码规范与文档:
 *    - Javadoc 注释规范。
 *    - **考点**: 能够阅读并解释复杂的类图 (Class Diagram) 和时序图。
 * 
 * ============================================================================
 * 备考建议 (Distinction Strategy):
 * 1. 动手画图：遇到多态问题时，画出内存中的对象引用关系。
 * 2. 关注“为什么”：不仅要知道怎么写，还要知道为什么这么设计（如接口解耦）。
 * 3. 历年真题：虽然 7710 是新课，但参考 COMP6710 的多态和集合大题非常有价值。
 * 4. 错误总结：建立一个“错题本”，记录所有编译错误和逻辑漏洞的原因。
 * ============================================================================
 */
